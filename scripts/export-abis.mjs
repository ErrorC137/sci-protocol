#!/usr/bin/env node
// Copies contract ABIs (from forge's out/) and deployment addresses into packages/shared,
// as typed `as const` TS so viem/wagmi infer function names and argument types.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const deployDir = join(root, "contracts", "deployments");
const dest = join(root, "packages", "shared", "src");
mkdirSync(dest, { recursive: true });

const CONTRACTS = [
  "ProjectRegistry",
  "MilestoneEscrow",
  "FundingPool",
  "SCIFraction",
  "AttestationRegistry",
  "MockUSDC",
];

let abis = "// AUTO-GENERATED by scripts/export-abis.mjs - do not edit.\n\n";
const abiJson = {};
for (const name of CONTRACTS) {
  const file = join(out, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) throw new Error(`Missing ${file}. Run \`forge build\` in contracts/ first.`);
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  abiJson[name] = abi;
  abis += `export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(dest, "abis.ts"), abis);
// Creation bytecode for the in-browser deploy page (apps/web/app/(app)/setup), loaded only on that page.
const bytecode = {};
for (const name of CONTRACTS) {
  bytecode[name] = JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8")).bytecode.object;
}
writeFileSync(join(root, "apps", "web", "lib", "bytecode.json"), JSON.stringify(bytecode));
// Same ABIs as plain JSON for the Python event indexer.
writeFileSync(join(root, "packages", "shared", "abis.json"), JSON.stringify(abiJson));

const deployments = {};
if (existsSync(deployDir)) {
  for (const f of readdirSync(deployDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(deployDir, f), "utf8"));
    deployments[d.chainId] = d;
  }
}
writeFileSync(
  join(dest, "deployments.ts"),
  "// AUTO-GENERATED by scripts/export-abis.mjs from contracts/deployments/*.json - do not edit.\n\n" +
    "export type Deployment = {\n  chainId: number;\n  startBlock: number;\n  deployer: `0x${string}`;\n  attestor: `0x${string}`;\n" +
    "  MockUSDC: `0x${string}`;\n  ProjectRegistry: `0x${string}`;\n  AttestationRegistry: `0x${string}`;\n" +
    "  SCIFraction: `0x${string}`;\n  MilestoneEscrow: `0x${string}`;\n  FundingPool: `0x${string}`;\n};\n\n" +
    `export const deployments: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)};\n`,
);
console.log(`ABIs for ${CONTRACTS.length} contracts and ${Object.keys(deployments).length} deployment(s) -> packages/shared/src`);
