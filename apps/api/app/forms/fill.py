"""Render reviewed values back out: filled AcroForm PDF, web-form payload, or a copy-paste pack."""

from __future__ import annotations

import io

from pypdf import PdfReader, PdfWriter

from ..models.schemas import Application, FilledField, FormTemplate, Grant


def _on_state(field: dict) -> str:
    for s in field.get("/_States_") or []:
        if s != "/Off":
            return s
    return "/Yes"


def _as_text(v) -> str:
    if v is None:
        return ""
    if isinstance(v, list):
        return ", ".join(v)
    if isinstance(v, bool):
        return "Yes" if v else "No"
    return str(v)


def fill_pdf(data: bytes, fields: list[FilledField]) -> bytes:
    reader = PdfReader(io.BytesIO(data))
    pdf_fields = reader.get_fields() or {}
    writer = PdfWriter(clone_from=reader)

    values: dict[str, str] = {}
    for f in fields:
        spec = pdf_fields.get(f.field_id)
        if spec is None or f.value in (None, ""):
            continue
        if spec.get("/FT") == "/Btn":
            if f.type == "radio" and isinstance(f.value, str):
                values[f.field_id] = "/" + f.value.lstrip("/")
            else:
                values[f.field_id] = _on_state(spec) if f.value is True else "/Off"
        else:
            values[f.field_id] = _as_text(f.value)

    for page in writer.pages:
        writer.update_page_form_field_values(page, values, auto_regenerate=False)
    # Ask viewers to regenerate appearances (needed for non-Latin scripts such as Thai).
    writer.set_need_appearances_writer(True)
    buf = io.BytesIO()
    writer.write(buf)
    return buf.getvalue()


def web_payload(app: Application) -> dict:
    return {f.field_id: f.value for f in app.fields if f.value not in (None, "")}


def copy_paste_pack(app: Application, grant: Grant, template: FormTemplate) -> str:
    lines = [
        f"# {grant.title}",
        f"Funder: {grant.funder_name or '-'}  ",
        f"Form: {template.title or template.form_url}  ",
        f"Reviewed by applicant: {app.reviewed_at:%Y-%m-%d %H:%M UTC}" if app.reviewed_at else "NOT YET REVIEWED",
        "",
        "> Generated by SCI Protocol from a non-confidential profile and reviewed by the applicant.",
        "> Paste each answer into the funder's own form. SCI Protocol never submits on your behalf.",
        "",
    ]
    for f in app.fields:
        lines.append(f"## {f.label}{' *' if f.required else ''}")
        lines.append(_as_text(f.value) or "_(left blank)_")
        lines.append("")
    return "\n".join(lines)
