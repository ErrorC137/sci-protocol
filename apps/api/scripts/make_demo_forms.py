"""Generates the demo application forms in apps/api/demo_forms/.

These are GENERIC forms built to exercise the three parsing paths (fillable PDF x2, HTML x1). They are
not any funder's official form, and say so on their face. Swap in official forms via `form_url` in
data/seed/grants.yaml (or the upload button in the app) when you have them.

    python scripts/make_demo_forms.py
"""

from __future__ import annotations

from pathlib import Path

from reportlab.lib.colors import HexColor, black, white
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

OUT = Path(__file__).resolve().parent.parent / "demo_forms"
W, H = A4
M = 50
INK = HexColor("#1f2937")
MUTED = HexColor("#6b7280")
BORDER = HexColor("#9ca3af")


class Form:
    def __init__(self, path: Path, title: str, subtitle: str):
        self.c = canvas.Canvas(str(path), pagesize=A4)
        self.c.setTitle(title)
        self.title, self.subtitle = title, subtitle
        self.page = 0
        self._new_page()

    def _new_page(self):
        if self.page:
            self.c.showPage()
        self.page += 1
        c = self.c
        c.setFillColor(HexColor("#fef3c7"))
        c.rect(0, H - 34, W, 34, fill=1, stroke=0)
        c.setFillColor(HexColor("#92400e"))
        c.setFont("Helvetica-Bold", 8.5)
        c.drawString(M, H - 21, "DEMO FORM - generated by SCI Protocol to demonstrate pre-fill. Not an official funder document.")
        c.setFillColor(INK)
        c.setFont("Helvetica-Bold", 15)
        c.drawString(M, H - 64, self.title)
        c.setFont("Helvetica", 9)
        c.setFillColor(MUTED)
        c.drawString(M, H - 78, self.subtitle + f"   |   Page {self.page}")
        self.y = H - 104

    def need(self, h: float):
        if self.y - h < 60:
            self._new_page()

    def section(self, text: str):
        self.need(40)
        self.y -= 8
        self.c.setFillColor(INK)
        self.c.setFont("Helvetica-Bold", 11)
        self.c.drawString(M, self.y, text)
        self.c.setStrokeColor(BORDER)
        self.c.line(M, self.y - 4, W - M, self.y - 4)
        self.y -= 22

    def _label(self, label: str, required: bool):
        self.c.setFillColor(INK)
        self.c.setFont("Helvetica", 8.5)
        self.c.drawString(M, self.y, label + (" *" if required else ""))

    def text(self, name: str, label: str, required=False, maxlen=None, lines=1, width=None):
        h = 16 if lines == 1 else 12 * lines + 6
        self.need(h + 18)
        self._label(label, required)
        flags = " ".join(f for f in ("required" if required else "", "multiline" if lines > 1 else "") if f)
        # reportlab always writes /MaxLen (default 100), so set realistic limits explicitly.
        self.c.acroForm.textfield(name=name, tooltip=label, x=M, y=self.y - h - 4, width=width or (W - 2 * M), height=h,
                                  borderColor=BORDER, fillColor=white, textColor=black, fontSize=9, borderWidth=0.6,
                                  fieldFlags=flags, maxlen=maxlen or (3000 if lines > 1 else 200))
        self.y -= h + 18

    def choice(self, name: str, label: str, options: list[str], required=False):
        self.need(34)
        self._label(label, required)
        self.c.acroForm.choice(name=name, tooltip=label, value=options[0], options=options, x=M, y=self.y - 20,
                               width=260, height=16, borderColor=BORDER, fillColor=white, textColor=black,
                               fontSize=9, fieldFlags="combo" + (" required" if required else ""))
        self.y -= 34

    def checkboxes(self, items: list[tuple[str, str]], prefix: str = "", required: bool = False):
        self.need(18 * ((len(items) + 1) // 2) + 6)
        col = 0
        for name, label in items:
            x = M + col * (W - 2 * M) / 2
            self.c.acroForm.checkbox(name=name, tooltip=f"{prefix}{label}", x=x, y=self.y - 12, size=11,
                                     buttonStyle="check", borderColor=BORDER, fillColor=white, textColor=black,
                                     fieldFlags="required" if required else "")
            self.c.setFont("Helvetica", 8.5)
            self.c.setFillColor(INK)
            self.c.drawString(x + 16, self.y - 9, label)
            col ^= 1
            if col == 0:
                self.y -= 18
        if col == 1:
            self.y -= 18
        self.y -= 6

    def save(self):
        self.c.save()


def thai_grant(path: Path):
    f = Form(path, "Research & Innovation Grant Application", "Generic Thai-agency-style structure (demo)")
    f.section("Section A - Applicant")
    f.text("project_title", "Project title", required=True)
    f.text("pi_name", "Principal investigator name", required=True)
    f.text("pi_position", "Position")
    f.text("institution", "Organisation / institution name", required=True)
    f.text("email", "E-mail", required=True)
    f.text("phone", "Telephone")
    f.text("org_address", "Organisation address")
    f.text("country", "Country")
    f.choice("applicant_type", "Applicant type",
             ["Individual researcher", "University or research institute", "Registered startup", "SME", "Consortium"])
    f.text("registered", "Registered company? (Yes / No)")
    f.section("Section B - Project")
    f.text("research_field", "Field of research", required=True)
    f.text("technology_area", "Technology area")
    f.text("trl", "Technology readiness level (TRL 1-9)", required=True)
    f.text("dev_stage", "Current stage of development")
    f.text("keywords", "Keywords")
    f.text("amount_thb", "Amount requested (THB)", required=True)
    f.text("duration", "Project duration (months)", required=True)
    f._label("Use of funds (tick all that apply)", False)
    f.y -= 6
    f.checkboxes([
        ("use_equipment", "Equipment"), ("use_materials", "Materials & consumables"), ("use_personnel", "Personnel"),
        ("use_pilot", "Pilot run"), ("use_certification", "Testing & certification"), ("use_ip", "IP filing"),
    ], prefix="Use of funds: ")
    f.section("Section C - Proposal")
    f.text("summary", "Project summary (max 1500 characters)", required=True, maxlen=1500, lines=5)
    f.text("innovation", "Describe the innovation and what is new compared with existing solutions", required=True, lines=5)
    f.text("objectives", "Objectives", required=True, lines=4)
    f.text("workplan", "Work plan and milestones", required=True, lines=5)
    f.text("impact", "Expected impact and commercialisation pathway", lines=4)
    f.text("budget_justification", "Budget justification", lines=4)
    f.text("team", "Team and relevant experience", lines=4)
    f.section("Section D - Declaration")
    f.checkboxes([("declaration", "I declare that the information provided is true and correct")], required=True)
    f.text("applicant_signature", "Signature of applicant", width=260)
    f.text("date_signed", "Date", width=160)
    f.save()


